CREATE TABLE empresas (
    id_empresa NUMBER GENERATED BY DEFAULT AS IDENTITY (NOCACHE),
    rut VARCHAR2(12) NOT NULL,
    razon_social VARCHAR2(120) NOT NULL,
    plan VARCHAR2(10) DEFAULT 'BASICO' NOT NULL,
    activo NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT pk_empresas PRIMARY KEY (id_empresa),
    CONSTRAINT uq_empresas_rut UNIQUE (rut),
    CONSTRAINT ck_empresas_plan CHECK (plan IN ('BASICO', 'PREMIUM')),
    CONSTRAINT ck_empresas_activo CHECK (activo IN (0, 1))
);

CREATE TABLE categorias_ticket (
    id_categoria NUMBER GENERATED BY DEFAULT AS IDENTITY (NOCACHE),
    nombre VARCHAR2(80) NOT NULL,
    horas_sla NUMBER(5) NOT NULL,
    activo NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT pk_categorias_ticket PRIMARY KEY (id_categoria),
    CONSTRAINT uq_categorias_ticket_nombre UNIQUE (nombre),
    CONSTRAINT ck_categorias_ticket_sla CHECK (horas_sla > 0),
    CONSTRAINT ck_categorias_ticket_activo CHECK (activo IN (0, 1))
);

CREATE TABLE tecnicos (
    id_tecnico NUMBER GENERATED BY DEFAULT AS IDENTITY (NOCACHE),
    rut VARCHAR2(12) NOT NULL,
    nombre VARCHAR2(120) NOT NULL,
    email VARCHAR2(150) NOT NULL,
    activo NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT pk_tecnicos PRIMARY KEY (id_tecnico),
    CONSTRAINT uq_tecnicos_rut UNIQUE (rut),
    CONSTRAINT uq_tecnicos_email UNIQUE (email),
    CONSTRAINT ck_tecnicos_activo CHECK (activo IN (0, 1))
);

CREATE TABLE tickets (
    id_ticket NUMBER GENERATED BY DEFAULT AS IDENTITY (NOCACHE),
    id_empresa NUMBER NOT NULL,
    id_categoria NUMBER NOT NULL,
    id_tecnico NUMBER,
    titulo VARCHAR2(150) NOT NULL,
    descripcion CLOB NOT NULL,
    prioridad VARCHAR2(10) DEFAULT 'MEDIA' NOT NULL,
    fecha_creacion TIMESTAMP WITH TIME ZONE DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    fecha_cierre TIMESTAMP WITH TIME ZONE,
    estado VARCHAR2(15) DEFAULT 'ABIERTO' NOT NULL,
    CONSTRAINT pk_tickets PRIMARY KEY (id_ticket),
    CONSTRAINT fk_tickets_empresa FOREIGN KEY (id_empresa) REFERENCES empresas(id_empresa),
    CONSTRAINT fk_tickets_categoria FOREIGN KEY (id_categoria) REFERENCES categorias_ticket(id_categoria),
    CONSTRAINT fk_tickets_tecnico FOREIGN KEY (id_tecnico) REFERENCES tecnicos(id_tecnico),
    CONSTRAINT ck_tickets_prioridad CHECK (prioridad IN ('BAJA', 'MEDIA', 'ALTA', 'CRITICA')),
    CONSTRAINT ck_tickets_estado CHECK (estado IN ('ABIERTO', 'ASIGNADO', 'EN_PROGRESO', 'RESUELTO', 'CERRADO')),
    CONSTRAINT ck_tickets_cierre CHECK (fecha_cierre IS NULL OR fecha_cierre >= fecha_creacion)
);

CREATE TABLE comentarios_ticket (
    id_comentario NUMBER GENERATED BY DEFAULT AS IDENTITY (NOCACHE),
    id_ticket NUMBER NOT NULL,
    numero NUMBER(6) NOT NULL,
    fecha TIMESTAMP WITH TIME ZONE DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    autor VARCHAR2(120) NOT NULL,
    texto CLOB NOT NULL,
    CONSTRAINT pk_comentarios_ticket PRIMARY KEY (id_ticket, numero),
    CONSTRAINT uq_comentarios_ticket_id UNIQUE (id_comentario),
    CONSTRAINT fk_comentarios_ticket_ticket FOREIGN KEY (id_ticket) REFERENCES tickets(id_ticket),
    CONSTRAINT ck_comentarios_ticket_numero CHECK (numero > 0)
);

CREATE INDEX ix_tickets_empresa ON tickets(id_empresa);
CREATE INDEX ix_tickets_categoria ON tickets(id_categoria);
CREATE INDEX ix_tickets_tecnico ON tickets(id_tecnico);
CREATE INDEX ix_comentarios_ticket_ticket ON comentarios_ticket(id_ticket);
CREATE INDEX ix_tickets_estado_prioridad ON tickets(estado, prioridad);

